                <p class="lead">ClearMyRide ("we," "our," or "us") is committed to protecting your privacy. This Privacy Notice explains how we collect, use, share, and protect your personal information when you use our services, including our website, intake forms, communications, and citation or renewal support processes.
                    We designed this policy to comply with Maryland state regulations governing Personally Identifiable Information (PII), Maryland Transportation Article §12-301 et seq. (regarding Motor Vehicle Administration records), and applicable federal privacy standards, including the Federal Trade Commission's Fair Information Practice Principles (FIPPs).</p>

                <section aria-labelledby="s1">
                    <div class="sec-head">
                        <div class="num">1</div>
                        <div class="sec-title" id="s1">Information We Collect</div>
                    </div>
                    <p>We collect the following categories of data:</p>
                    <p><strong>Personal Identification Information:</strong> name, address, date of birth, driver's license number, and contact information (email, phone).</p>
                    <p><strong>Vehicle Information:</strong> VIN, plate number, tag expiration dates, citation details, registration history.</p>
                    <p><strong>Supporting Documentation:</strong> uploaded forms, letters, or screenshots related to MVA citations, renewals, or verifications.</p>
                    <p><strong>Payment Information:</strong> billing details necessary to process fees (handled securely via PCI-DSS-compliant payment processors; we never store full card numbers).</p>
                    <p><strong>Technical Data:</strong> IP addresses, device identifiers, browser type, and analytics data (Google Analytics, form logs) to understand platform performance.</p>
                    <p>We collect this data directly from you, from state or local MVA systems (when authorized), and from third-party data providers as needed to verify or process your request.</p>
                </section>

                <section aria-labelledby="s2">
                    <div class="sec-head">
                        <div class="num">2</div>
                        <div class="sec-title" id="s2">How We Use Your Information</div>
                    </div>
                    <p>Your information is used strictly for service delivery, compliance, and improvement. Specifically:</p>
                    <ul>
                        <li>To process and resolve your registration renewal, citation, or driver's license request.</li>
                        <li>To verify identity and authorization before interacting with MVA systems or citation databases.</li>
                        <li>To communicate updates about your case via email, SMS, or customer dashboard.</li>
                        <li>To track internal metrics such as average resolution time, system accuracy, and customer satisfaction (we use anonymized data for reporting).</li>
                        <li>To enhance product quality through analytics, bug tracking, and feature optimization.</li>
                        <li>To comply with legal obligations, such as record retention requirements under Maryland and federal law.</li>
                    </ul>
                    <p>We may also use anonymized data to analyze patterns (e.g., average citation resolution times or regional service demand). No personally identifying data is ever sold or disclosed for marketing purposes.</p>
                </section>

                <section aria-labelledby="s3">
                    <div class="sec-head">
                        <div class="num">3</div>
                        <div class="sec-title" id="s3">Legal Basis for Processing</div>
                    </div>
                    <p>Our processing is grounded in:</p>
                    <ul>
                        <li><strong>Consent:</strong> You provide consent when submitting the intake form.</li>
                        <li><strong>Contractual necessity:</strong> We use your data to perform the service you request.</li>
                        <li><strong>Legal obligation:</strong> We comply with applicable data retention and reporting rules (e.g., Maryland MVA documentation standards).</li>
                        <li><strong>Legitimate interest:</strong> We maintain minimal logs and anonymized records to improve performance and protect system integrity.</li>
                    </ul>
                </section>

                <section aria-labelledby="s4">
                    <div class="sec-head">
                        <div class="num">4</div>
                        <div class="sec-title" id="s4">Data Sharing and Disclosure</div>
                    </div>
                    <p>We share data only where necessary:</p>
                    <ul>
                        <li><strong>Service Providers:</strong> Trusted vendors (hosting, email, text notifications, payment processors) operating under signed confidentiality and data protection agreements.</li>
                        <li><strong>Maryland MVA & State Systems:</strong> When authorized, we submit or retrieve limited records for verification or processing.</li>
                        <li><strong>Law Enforcement:</strong> Only if required by law or official subpoena.</li>
                    </ul>
                    <p>All third-party processors must meet or exceed industry data security standards (ISO/IEC 27001, SOC 2 Type II) and comply with Maryland's Personal Information Protection Act (Md. Code Com. Law §14-3501 et seq.).</p>
                </section>

                <section aria-labelledby="s5">
                    <div class="sec-head">
                        <div class="num">5</div>
                        <div class="sec-title" id="s5">Data Retention and Storage</div>
                    </div>
                    <p>We retain user data for as long as needed to complete the service and maintain compliance records (typically 12–18 months).</p>
                    <p>Payment records are retained only as long as legally required for financial reporting.</p>
                    <p>After retention periods expire, we anonymize or permanently delete data from all systems.</p>
                    <p>All data is stored on encrypted servers located in the United States, in accordance with NIST SP 800-171 guidelines for data protection.</p>
                </section>

                <section aria-labelledby="s6">
                    <div class="sec-head">
                        <div class="num">6</div>
                        <div class="sec-title" id="s6">Security Measures</div>
                    </div>
                    <p>We follow recognized cybersecurity frameworks to safeguard your data, including:</p>
                    <ul>
                        <li><strong>Encryption:</strong> All transmissions (web, email, SMS) are encrypted via SSL/TLS 1.2+.</li>
                        <li><strong>Access Control:</strong> Data is restricted to authorized personnel under least-privilege access.</li>
                        <li><strong>Audit & Monitoring:</strong> Regular vulnerability scans and activity logging per NIST SP 800-53 controls.</li>
                        <li><strong>Incident Response:</strong> Breach notification procedures align with Maryland's Data Breach Notification Law (Md. Code Com. Law §14-3504), ensuring prompt disclosure within statutory timelines.</li>
                    </ul>
                </section>

                <section aria-labelledby="s7">
                    <div class="sec-head">
