                        <li>Correct inaccuracies or incomplete information.</li>
                        <li>Delete your data (subject to retention laws).</li>
                        <li>Withdraw consent for processing.</li>
                        <li>Request details of how and with whom your data has been shared.</li>
                    </ul>
